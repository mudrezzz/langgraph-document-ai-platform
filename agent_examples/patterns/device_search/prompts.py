# ── 4. Criterion evaluation with evidence ─────────────────────────────────────

EVALUATE_CRITERION_PROMPT = """\
Ты эксперт по электронике. Оцени устройство по одному критерию на основе найденных данных.

Устройство: {device_name}
Критерий: {criterion_name}
Пороговые значения: {thresholds}
Описание критерия: {criterion_description}

Технические характеристики устройства:
{raw_specs}

Найденные данные (бенчмарки, обзоры):
{evidence_snippets}

═══════════════════════════════════════════
ШКАЛА ОЦЕНОК — соблюдай СТРОГО:
  1.0   параметр превышает порог на >20%
  0.7–0.89  соответствует порогу или незначительно превышает
  0.5–0.69  близко к порогу (<15% отклонения), но НЕ достигает
  0.3–0.49  заметно ниже порога
  0.0–0.29  значительно ниже порога или данных нет

КРИТИЧЕСКОЕ ПРАВИЛО СОГЛАСОВАННОСТИ:
  Если в поле "assessment" есть слова "не достигает", "ниже порога",
  "не соответствует" — score ОБЯЗАН быть < 0.65.
  Если assessment говорит "превышает", "соответствует" — score >= 0.7.
═══════════════════════════════════════════

Верни ТОЛЬКО JSON:
{{
  "score": 0.0-1.0,
  "assessment": "1-2 предложения: конкретные числа + вывод соответствие/несоответствие порогу",
  "evidence_used": [
    {{
      "source_url": "url или ''",
      "title": "заголовок источника",
      "snippet": "ключевой фрагмент (до 150 символов)",
      "evidence_type": "benchmark / expert_review / official_specs / user_review",
      "confidence": 0.0-1.0
    }}
  ],
  "unresolved_gaps": ["чего не удалось найти / проверить"]
}}
"""

